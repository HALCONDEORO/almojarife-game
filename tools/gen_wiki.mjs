// Generates the statistics tables of the internal wiki from the code constants, so the docs cannot drift.
// Usage: node tools/gen_wiki.mjs          (writes docs/wiki/generated/*.md and docs/wiki/generated/es/*.md)
//        node tools/gen_wiki.mjs --check  (exit 1 if a committed file differs; used by test/wiki-generated.test.mjs)
import { writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SHIP_TYPES, FEE } from "../src/sim/trade.mjs";
import { WEAPON_TYPES, MAX_CANNONS } from "../src/game/crew.mjs";
import { CLASSES, TOLERANCE, classShares, PER_1000, OPTIONAL_PER_1000 } from "../src/sim/classes.mjs";
import { NEED_GROUP } from "../src/sim/needs.mjs";
import { POTTERY, LEGUMES } from "../src/sim/optional_goods.mjs";
import { COASTS } from "../src/game/charts.mjs";
import { realmOf } from "../src/game/marque.mjs";
import { START_YEAR } from "../src/sim/clock.mjs";

const here0 = dirname(fileURLToPath(import.meta.url));
const WORLD = JSON.parse(readFileSync(join(here0, "..", "data", "world.json"), "utf8"));
const WORLD_GOODS = WORLD.goods;
const REALMS = JSON.parse(readFileSync(join(here0, "..", "data", "realms.json"), "utf8"));

const HEAD = "<!-- Generated by tools/gen_wiki.mjs from the code constants. Do not edit by hand: change the code, run `node tools/gen_wiki.mjs`. -->\n";
const HEAD_ES = "<!-- Generado por tools/gen_wiki.mjs a partir de las constantes del código. No editar a mano: cambia el código y ejecuta `node tools/gen_wiki.mjs`. -->\n";
const row = (...c) => "| " + c.join(" | ") + " |\n";

// Game display names for the Spanish tables (web/main.mjs, T.es).
const ES_SHIP = { barca: "Barca", cog: "Coca", caravel: "Carabela", nao: "Nao" };
const ES_WEAPON = { ballista: "Balista", catapult: "Catapulta", cannon: "Cañón", bombard: "Bombarda" };
const ES_CLASS = { poor: "Pobres", middle: "Artesanos y mercaderes", rich: "Ricos" };
const ES_GOOD = { grain: "Trigo", fish: "Pescado", salt: "Sal", wool: "Lana", iron: "Hierro", ironware: "Herrajes", timber: "Madera", cloth: "Paño", olive_oil: "Aceite", wine: "Vino", silk: "Seda", sugar: "Azúcar", pepper: "Pimienta", saffron: "Azafrán", beer: "Cerveza", bricks: "Ladrillos", esparto: "Esparto", meat: "Carne", pottery: "Cerámica", legumes: "Legumbres", leather: "Cuero", soap: "Jabón" };
const ES_GROUP = { food: "Alimento", drink: "Bebida", luxury: "Lujo", clothing: "Ropa", household: "Hogar", materials: "Materiales", other: "Otros" };
const OPTIONAL_GOODS = [POTTERY, LEGUMES]; // flag-gated goods (on by default): src/sim/optional_goods.mjs
const COAST_NAME_EN = { luz: "Costa de la Luz", portugal: "Portuguese coast", cantabrico: "Cantabrian coast", levante: "Levante & Catalonia", baleares: "Balearics", rif: "The Rif", marruecos: "Atlantic Morocco", berberia: "Eastern Barbary" };
const COAST_NAME_ES = { luz: "Costa de la Luz", portugal: "Costa portuguesa", cantabrico: "Costa Cantábrica", levante: "Levante y Cataluña", baleares: "Baleares", rif: "El Rif", marruecos: "Marruecos atlántico", berberia: "Berbería oriental" };
const portsRows = (coastName, goodName, realmName) => {
  const rows = [];
  for (const k of Object.keys(COASTS)) {
    for (const cid of COASTS[k].ports) {
      const c = WORLD.cities.find((x) => x.id === cid);
      if (!c) continue;
      const r = realmOf(REALMS, cid, START_YEAR);
      rows.push([c.name + (c.river ? " ⚓" : ""), coastName(k), r ? realmName(r) : "—", c.pop, c.makes.map(goodName).join(", "), c.needs.map(goodName).join(", ")]);
    }
  }
  return rows;
};
const goodsRows = (name, group) => {
  const rows = [];
  const emit = (g, base, opt) => {
    const d = PER_1000[g] ?? OPTIONAL_PER_1000[g] ?? { poor: 0, middle: 0, rich: 0 };
    rows.push([name(g) + (opt ? " †" : ""), base, group(g), d.poor, d.middle, d.rich]);
  };
  for (const [g, v] of Object.entries(WORLD_GOODS)) emit(g, v.base, false);
  for (const o of OPTIONAL_GOODS) emit(o.good, o.base, true);
  return rows;
};

export function render() {
  const out = {};
  let s = HEAD + "# Ships and weapons (generated)\n\nSource: `SHIP_TYPES`, `FEE` in `src/sim/trade.mjs`; `WEAPON_TYPES`, `MAX_CANNONS` in `src/game/crew.mjs`. Type of data: game design values (assumed), not observed history.\n\n";
  s += "## Ships\n\n" + row("Ship", "Hold", "km/day", "Upkeep/day", "Price", "Build days", "Weapon slots");
  s += row("---", "---", "---", "---", "---", "---", "---");
  for (const [k, v] of Object.entries(SHIP_TYPES)) s += row(k, v.capacity, v.kmPerDay, v.upkeepPerDay, v.price, v.buildDays, MAX_CANNONS[k] ?? 0);
  s += `\nMarket fee on every deal, both sides: ${FEE * 100}%.\n\n## Ship weapons\n\n` + row("Weapon", "Price", "Power", "Upkeep/day") + row("---", "---", "---", "---");
  for (const [k, v] of Object.entries(WEAPON_TYPES)) s += row(k, v.price, v.power, v.upkeep);
  out["ships-and-weapons.md"] = s;

  let c = HEAD + "# Social classes (generated)\n\nSource: `CLASSES`, `TOLERANCE`, `classShares` in `src/sim/classes.mjs`. Type of data: game design values (assumed).\n\n";
  c += "## Price tolerance\n\nHighest price, as a multiple of the base price, that each class still pays.\n\n" + row("Class", "Tolerance") + row("---", "---");
  for (const k of CLASSES) c += row(k, TOLERANCE[k]);
  c += "\n## Share of the population by city size\n\n" + row("Population", ...CLASSES) + row("---", ...CLASSES.map(() => "---"));
  for (const pop of [2000, 8000, 14000, 22000]) { const sh = classShares(pop); c += row(pop, ...CLASSES.map((k) => (sh[k] * 100).toFixed(1) + "%")); }
  out["classes.md"] = c;

  let se = HEAD_ES + "# Barcos y armas (generado)\n\nFuente: `SHIP_TYPES`, `FEE` en `src/sim/trade.mjs`; `WEAPON_TYPES`, `MAX_CANNONS` en `src/game/crew.mjs`. Tipo de dato: valores de diseño del juego (supuestos), no historia observada.\n\n";
  se += "## Barcos\n\n" + row("Barco", "Bodega", "km/día", "Mantenimiento/día", "Precio", "Días de construcción", "Huecos de armas");
  se += row("---", "---", "---", "---", "---", "---", "---");
  for (const [k, v] of Object.entries(SHIP_TYPES)) se += row(ES_SHIP[k] ?? k, v.capacity, v.kmPerDay, v.upkeepPerDay, v.price, v.buildDays, MAX_CANNONS[k] ?? 0);
  se += `\nTasa de mercado en cada trato, a cargo de ambas partes: ${FEE * 100}%.\n\n## Armas de barco\n\n` + row("Arma", "Precio", "Potencia", "Mantenimiento/día") + row("---", "---", "---", "---");
  for (const [k, v] of Object.entries(WEAPON_TYPES)) se += row(ES_WEAPON[k] ?? k, v.price, v.power, v.upkeep);
  out["es/ships-and-weapons.md"] = se;

  let ce = HEAD_ES + "# Clases sociales (generado)\n\nFuente: `CLASSES`, `TOLERANCE`, `classShares` en `src/sim/classes.mjs`. Tipo de dato: valores de diseño del juego (supuestos).\n\n";
  ce += "## Tolerancia de precio\n\nPrecio más alto, como múltiplo del precio base, que cada clase aún paga.\n\n" + row("Clase", "Tolerancia") + row("---", "---");
  for (const k of CLASSES) ce += row(ES_CLASS[k] ?? k, TOLERANCE[k]);
  ce += "\n## Reparto de la población por tamaño de ciudad\n\n" + row("Población", ...CLASSES.map((k) => ES_CLASS[k] ?? k)) + row("---", ...CLASSES.map(() => "---"));
  for (const pop of [2000, 8000, 14000, 22000]) { const sh = classShares(pop); ce += row(pop, ...CLASSES.map((k) => (sh[k] * 100).toFixed(1) + "%")); }
  out["es/classes.md"] = ce;

  let gn = HEAD + "# Goods (generated)\n\nSource: `goods` in `data/world.json` (base prices), `PER_1000` and `OPTIONAL_PER_1000` in `src/sim/classes.mjs` (demand), `NEED_GROUP` in `src/sim/needs.mjs` (group), `src/sim/optional_goods.mjs` (optional goods). Type of data: game design values (assumed), except the sourced rates noted in those files.\n\nDemand: units bought per 1000 citizens per day at the base price. Above the base price each class buys less, down to zero at its tolerance ([classes table](classes.md)).\n\n";
  gn += row("Good", "Base price", "Need group", "Poor", "Middle", "Rich") + row("---", "---", "---", "---", "---", "---");
  for (const r of goodsRows((g) => g, (g) => NEED_GROUP[g] ?? "other")) gn += row(...r);
  gn += "\n† Optional good: it joins the world only when its flag is on (default on; `src/sim/optional_goods.mjs`).\n";
  out["goods.md"] = gn;

  let ge = HEAD_ES + "# Mercancías (generado)\n\nFuente: `goods` en `data/world.json` (precios base), `PER_1000` y `OPTIONAL_PER_1000` en `src/sim/classes.mjs` (demanda), `NEED_GROUP` en `src/sim/needs.mjs` (grupo), `src/sim/optional_goods.mjs` (mercancías opcionales). Tipo de dato: valores de diseño del juego (supuestos), salvo las tasas con fuente anotadas en esos archivos.\n\nDemanda: unidades compradas por cada 1000 vecinos al día al precio base. Por encima del precio base cada clase compra menos, hasta cero en su tolerancia ([tabla de clases](classes.md)).\n\n";
  ge += row("Mercancía", "Precio base", "Grupo", "Pobres", "Artesanos y mercaderes", "Ricos") + row("---", "---", "---", "---", "---", "---");
  for (const r of goodsRows((g) => ES_GOOD[g] ?? g, (g) => ES_GROUP[NEED_GROUP[g] ?? "other"])) ge += row(...r);
  ge += "\n† Mercancía opcional: solo entra en el mundo cuando su bandera está activa (activa por defecto; `src/sim/optional_goods.mjs`).\n";
  out["es/goods.md"] = ge;

  let pn = HEAD + "# Ports (generated)\n\nSource: `cities` in `data/world.json` (33 ports with their population at the 1480 start; `pop1500` keeps the historical figure with its source in `docs/port-sources.md`), `COASTS` in `src/game/charts.mjs`, holdings in `data/realms.json` read at the start year with `realmOf` (`src/game/marque.mjs`, `START_YEAR` in `src/sim/clock.mjs`). Type of data: institutional for holdings and historical populations (each row carries its source in the data files); the rest is game design (assumed). ⚓ marks a river port.\n\nA port starts unknown unless it is home; sailing, charts and rumours reveal it (see [rules.md](rules.md#port-information-charts-rumours-and-informants)).\n\n";
  pn += row("Port", "Coast", "Realm (1480)", "Pop. at start", "Produces", "Needs") + row("---", "---", "---", "---", "---", "---");
  for (const r of portsRows((k) => COAST_NAME_EN[k] ?? k, (g) => g, (r) => REALMS.realms[r]?.name?.en ?? r)) pn += row(...r);
  out["ports.md"] = pn;

  let pe = HEAD_ES + "# Puertos (generado)\n\nFuente: `cities` en `data/world.json` (33 puertos con su población al inicio de 1480; `pop1500` guarda la cifra histórica con su fuente en `docs/port-sources.md`), `COASTS` en `src/game/charts.mjs`, tenencias de `data/realms.json` leídas en el año de inicio con `realmOf` (`src/game/marque.mjs`, `START_YEAR` en `src/sim/clock.mjs`). Tipo de dato: institucional para tenencias y poblaciones históricas (cada fila lleva su fuente en los archivos de datos); lo demás es diseño del juego (supuesto). ⚓ marca un puerto fluvial.\n\nUn puerto empieza desconocido salvo que sea el de origen; navegar, las cartas y los rumores lo revelan (ver [rules.md](rules.md#información-portuaria-cartas-rumores-e-informantes)).\n\n";
  pe += row("Puerto", "Costa", "Reino (1480)", "Pob. inicial", "Produce", "Necesita") + row("---", "---", "---", "---", "---", "---");
  for (const r of portsRows((k) => COAST_NAME_ES[k] ?? k, (g) => ES_GOOD[g] ?? g, (r) => REALMS.realms[r]?.name?.es ?? r)) pe += row(...r);
  out["es/ports.md"] = pe;
  return out;
}

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "..", "docs", "wiki", "generated");
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const files = render();
  if (process.argv.includes("--check")) {
    let bad = 0;
    for (const [n, t] of Object.entries(files)) { let cur = ""; try { cur = readFileSync(join(dir, n), "utf8"); } catch {} if (cur !== t) { console.error("out of date: docs/wiki/generated/" + n); bad++; } }
    process.exit(bad ? 1 : 0);
  }
  for (const [n, t] of Object.entries(files)) { mkdirSync(dirname(join(dir, n)), { recursive: true }); writeFileSync(join(dir, n), t); }
}
