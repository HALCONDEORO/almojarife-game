// Generates the statistics tables of the internal wiki from the code constants, so the docs cannot drift.
// Usage: node tools/gen_wiki.mjs          (writes docs/wiki/generated/*.md and docs/wiki/generated/es/*.md)
//        node tools/gen_wiki.mjs --check  (exit 1 if a committed file differs; used by test/wiki-generated.test.mjs)
import { writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SHIP_TYPES, FEE } from "../src/sim/trade.mjs";
import { WEAPON_TYPES, MAX_CANNONS } from "../src/game/crew.mjs";
import { CLASSES, TOLERANCE, classShares } from "../src/sim/classes.mjs";

const HEAD = "<!-- Generated by tools/gen_wiki.mjs from the code constants. Do not edit by hand: change the code, run `node tools/gen_wiki.mjs`. -->\n";
const HEAD_ES = "<!-- Generado por tools/gen_wiki.mjs a partir de las constantes del código. No editar a mano: cambia el código y ejecuta `node tools/gen_wiki.mjs`. -->\n";
const row = (...c) => "| " + c.join(" | ") + " |\n";

// Game display names for the Spanish tables (web/main.mjs, T.es).
const ES_SHIP = { barca: "Barca", cog: "Coca", caravel: "Carabela", nao: "Nao" };
const ES_WEAPON = { ballista: "Balista", catapult: "Catapulta", cannon: "Cañón", bombard: "Bombarda" };
const ES_CLASS = { poor: "Pobres", middle: "Artesanos y mercaderes", rich: "Ricos" };

export function render() {
  const out = {};
  let s = HEAD + "# Ships and weapons (generated)\n\nSource: `SHIP_TYPES`, `FEE` in `src/sim/trade.mjs`; `WEAPON_TYPES`, `MAX_CANNONS` in `src/game/crew.mjs`. Type of data: game design values (assumed), not observed history.\n\n";
  s += "## Ships\n\n" + row("Ship", "Hold", "km/day", "Upkeep/day", "Price", "Build days", "Weapon slots");
  s += row("---", "---", "---", "---", "---", "---", "---");
  for (const [k, v] of Object.entries(SHIP_TYPES)) s += row(k, v.capacity, v.kmPerDay, v.upkeepPerDay, v.price, v.buildDays, MAX_CANNONS[k] ?? 0);
  s += `\nMarket fee on every deal, both sides: ${FEE * 100}%.\n\n## Ship weapons\n\n` + row("Weapon", "Price", "Power", "Upkeep/day") + row("---", "---", "---", "---");
  for (const [k, v] of Object.entries(WEAPON_TYPES)) s += row(k, v.price, v.power, v.upkeep);
  out["ships-and-weapons.md"] = s;

  let c = HEAD + "# Social classes (generated)\n\nSource: `CLASSES`, `TOLERANCE`, `classShares` in `src/sim/classes.mjs`. Type of data: game design values (assumed).\n\n";
  c += "## Price tolerance\n\nHighest price, as a multiple of the base price, that each class still pays.\n\n" + row("Class", "Tolerance") + row("---", "---");
  for (const k of CLASSES) c += row(k, TOLERANCE[k]);
  c += "\n## Share of the population by city size\n\n" + row("Population", ...CLASSES) + row("---", ...CLASSES.map(() => "---"));
  for (const pop of [2000, 8000, 14000, 22000]) { const sh = classShares(pop); c += row(pop, ...CLASSES.map((k) => (sh[k] * 100).toFixed(1) + "%")); }
  out["classes.md"] = c;

  let se = HEAD_ES + "# Barcos y armas (generado)\n\nFuente: `SHIP_TYPES`, `FEE` en `src/sim/trade.mjs`; `WEAPON_TYPES`, `MAX_CANNONS` en `src/game/crew.mjs`. Tipo de dato: valores de diseño del juego (supuestos), no historia observada.\n\n";
  se += "## Barcos\n\n" + row("Barco", "Bodega", "km/día", "Mantenimiento/día", "Precio", "Días de construcción", "Huecos de armas");
  se += row("---", "---", "---", "---", "---", "---", "---");
  for (const [k, v] of Object.entries(SHIP_TYPES)) se += row(ES_SHIP[k] ?? k, v.capacity, v.kmPerDay, v.upkeepPerDay, v.price, v.buildDays, MAX_CANNONS[k] ?? 0);
  se += `\nTasa de mercado en cada trato, a cargo de ambas partes: ${FEE * 100}%.\n\n## Armas de barco\n\n` + row("Arma", "Precio", "Potencia", "Mantenimiento/día") + row("---", "---", "---", "---");
  for (const [k, v] of Object.entries(WEAPON_TYPES)) se += row(ES_WEAPON[k] ?? k, v.price, v.power, v.upkeep);
  out["es/ships-and-weapons.md"] = se;

  let ce = HEAD_ES + "# Clases sociales (generado)\n\nFuente: `CLASSES`, `TOLERANCE`, `classShares` en `src/sim/classes.mjs`. Tipo de dato: valores de diseño del juego (supuestos).\n\n";
  ce += "## Tolerancia de precio\n\nPrecio más alto, como múltiplo del precio base, que cada clase aún paga.\n\n" + row("Clase", "Tolerancia") + row("---", "---");
  for (const k of CLASSES) ce += row(ES_CLASS[k] ?? k, TOLERANCE[k]);
  ce += "\n## Reparto de la población por tamaño de ciudad\n\n" + row("Población", ...CLASSES.map((k) => ES_CLASS[k] ?? k)) + row("---", ...CLASSES.map(() => "---"));
  for (const pop of [2000, 8000, 14000, 22000]) { const sh = classShares(pop); ce += row(pop, ...CLASSES.map((k) => (sh[k] * 100).toFixed(1) + "%")); }
  out["es/classes.md"] = ce;
  return out;
}

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "..", "docs", "wiki", "generated");
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const files = render();
  if (process.argv.includes("--check")) {
    let bad = 0;
    for (const [n, t] of Object.entries(files)) { let cur = ""; try { cur = readFileSync(join(dir, n), "utf8"); } catch {} if (cur !== t) { console.error("out of date: docs/wiki/generated/" + n); bad++; } }
    process.exit(bad ? 1 : 0);
  }
  for (const [n, t] of Object.entries(files)) { mkdirSync(dirname(join(dir, n)), { recursive: true }); writeFileSync(join(dir, n), t); }
}
