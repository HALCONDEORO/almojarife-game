#!/usr/bin/env python3
"""Clip Natural Earth 50m public-domain land to the game's chart. Same source as background.webp.
Run after tools/fetch_data.sh. Generated coordinates are geometry, not historical claims.
"""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
w=json.loads((root/'data/world.json').read_text());p=w['cities']+list(w['waypoints'].values())
b=(min(v['lon'] for v in p)-1,min(v['lat'] for v in p)-1,max(v['lon'] for v in p)+1,max(v['lat'] for v in p)+1)
def clip(poly):
    for axis,edge,sign in [(0,b[0],1),(0,b[2],-1),(1,b[1],1),(1,b[3],-1)]:
        out=[]
        for a,c in zip(poly[-1:]+poly[:-1],poly):
            ia=(a[axis]-edge)*sign>=0;ic=(c[axis]-edge)*sign>=0
            if ia!=ic:
                t=(edge-a[axis])/(c[axis]-a[axis]);out.append([a[0]+t*(c[0]-a[0]),a[1]+t*(c[1]-a[1])])
            if ic:out.append(c)
        poly=out
        if not poly:break
    return [[round(x,5),round(y,5)] for x,y in poly]
rings=[]
for f in json.loads((root/'data/ne_50m_land.geojson').read_text())['features']:
    g=f['geometry'];polys=[g['coordinates']] if g['type']=='Polygon' else g['coordinates']
    for poly in polys:
        for r in poly:
            c=clip(r)
            if len(c)>=3:rings.append(c)
text='// Generated by tools/gen_political_land.py from Natural Earth 50m public-domain land.\n// Same geometry and projection as background.webp; no historical borders.\nexport const CHART_LAND='+json.dumps(rings,separators=(',',':'))+';\n'
(root/'src/view/chartland.mjs').write_text(text)
print(len(rings),'rings',len(text),'bytes')
